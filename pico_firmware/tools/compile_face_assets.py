#!/usr/bin/env python3
"""Deterministically pack the checked-in 1-bit BMP primitives. Standard library only."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / 'bmp-primitives/pico_face_primitives_pack_v2'
OUTPUT = ROOT / 'lib/pico_core/include/pico/face_assets.hpp'
STYLES = ['modern','chibi','anime','retro_ibm','mecha','vintage_cartoon','minimal_emoticon','kawaii_mascot']

def bitmap(path):
    b = path.read_bytes()
    offset, dib = struct.unpack_from('<II', b, 10)
    w, h, planes, bits, compression = struct.unpack_from('<iiHHI', b, 18)
    if b[:2] != b'BM' or dib < 40 or bits != 1 or planes != 1 or compression != 0 or w <= 0 or not h:
        raise ValueError(f'Unsupported BMP: {path}')
    palette = b[14+dib:14+dib+8]
    on = 1 if sum(palette[4:7]) > sum(palette[:3]) else 0
    height, stride = abs(h), ((w + 31)//32)*4
    packed = bytearray(((w+7)//8)*height)
    for y in range(height):
        src_y = height-1-y if h > 0 else y
        for x in range(w):
            value = (b[offset+src_y*stride+x//8] >> (7-x%8)) & 1
            if value == on: packed[y*((w+7)//8)+x//8] |= 1 << (7-x%8)
    return w, height, packed

def generate():
    manifest = json.loads((PACK/'manifest.json').read_text())
    items = [i for i in manifest if i['group'] == 'base_families']
    lines = ['// Generated by tools/compile_face_assets.py; do not edit.', '#pragma once',
             '#include <cstdint>', 'namespace pico::assets {',
             'struct Bitmap { std::uint8_t width, height; const std::uint8_t *data; };',
             'struct Face { Bitmap left, right, brow_left, brow_right, mouth; };']
    lookup = {}
    digest = hashlib.sha256()
    for i in items:
        key = (i['style'], i['category'], i['name'])
        symbol = '_'.join(key)
        path = PACK / i['file']
        digest.update(path.read_bytes())
        w,h,data = bitmap(path)
        if (w,h) != (i['width'],i['height']): raise ValueError(f'Manifest size mismatch: {path}')
        lines.append(f'inline constexpr std::uint8_t {symbol}[] = {{'+','.join(f'0x{v:02x}' for v in data)+'};')
        lookup[key] = f'Bitmap{{{w},{h},{symbol}}}'
    lines += ['inline constexpr Face faces[8][5] = {']
    for style in STYLES:
        def choose(category, candidates):
            for name in candidates:
                if (style,category,name) in lookup: return lookup[style,category,name]
            raise ValueError((style,category,candidates))
        neutral = ['capsule','solid','open','block','visor','pie','dot','bean']
        eyes = [neutral, ['happy','caret','scan']+neutral,
                ['ring','pie_up','hex','sparkle']+neutral,
                ['sleepy','half_lid','line','dash','scan']+neutral,
                ['ring','hex','sparkle','open']+neutral]
        mouths = [['flat','underscore','tiny_smile'], ['smile','grin','tiny_smile','grille'],
                  ['o','open','flat'], ['flat','underscore','tiny_smile'], ['open','o']]
        lines.append('{ // '+style)
        for mood in range(5):
            brow = ['raised','angular','soft','flat'] if mood in [2,4] else ['soft','flat','angular']
            parts = [choose('eyes',[n+'_left' for n in eyes[mood]]),
                     choose('eyes',[n+'_right' for n in eyes[mood]]),
                     choose('brows',[n+'_left' for n in brow]),
                     choose('brows',[n+'_right' for n in brow]),choose('mouths',mouths[mood])]
            lines.append('{'+','.join(parts)+'},')
        lines.append('},')
    lines += ['};', f'inline constexpr const char *source_sha256 = "{digest.hexdigest()}";',
              'inline constexpr const char *theme_names[8] = {"MODERN","CHIBI","ANIME","RETRO IBM","MECHA","CARTOON","MINIMAL","KAWAII"};','}']
    return '\n'.join(lines)+'\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content: raise SystemExit('Packed assets are stale')
        print('Packed face assets match source BMPs')
    else:
        OUTPUT.write_text(content)
        print(OUTPUT)
